def test_cython_can_regenerate_a_file_with_a_modification_notice(monkeypatch, tmp_path):
    scripts = Path(__file__).resolve().parents[1] / "scripts"
    monkeypatch.syspath_prepend(str(scripts))
    from bootstrap import regenerate_extension
    source = tmp_path / "example.pyx"
    original = b"cpdef double add_one(double x):\n    return x + 1\n"
    source.write_bytes(original)
    source.with_suffix(".c").write_text("/* Previous distributor modification notice */\n/* Generated by Cython */\n")
    regenerate_extension(source)
    first = source.with_suffix(".c").read_bytes()
    assert b"NaNoBO modification" in first and b"Generated by Cython" in first and b"PyInit_example" in first
    regenerate_extension(source)
    assert source.read_bytes() == original
    assert source.with_suffix(".c").stat().st_size > 1000


